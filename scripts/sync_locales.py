"""Copy locales/en.json into desktop/plugin.js (the inline English fallback).

A disk plugin can only import the Hermes SDK and React, so the English catalog has to live
inside plugin.js; the other languages are fetched from the backend at runtime. Run after
editing locales/en.json:  python scripts/sync_locales.py   (tests fail when out of sync)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "// @@EN-BEGIN (generated by scripts/sync_locales.py from locales/en.json - do not edit)"
END = "// @@EN-END"


def en_block() -> str:
    data = json.loads((ROOT / "locales" / "en.json").read_text(encoding="utf-8"))
    data = {k: v for k, v in data.items() if not k.startswith("_")}
    return f"{BEGIN}\nconst EN = {json.dumps(data, ensure_ascii=False, indent=2)}\n{END}"


def current_block(js: str) -> str | None:
    if BEGIN not in js or END not in js:
        return None
    start = js.index(BEGIN)
    return js[start: js.index(END, start) + len(END)]


def main() -> int:
    path = ROOT / "desktop" / "plugin.js"
    js = path.read_text(encoding="utf-8")
    block = en_block()
    old = current_block(js)
    js = js.replace(old, block) if old else js.rstrip("\n") + "\n\n" + block + "\n"
    path.write_text(js, encoding="utf-8")
    print("desktop/plugin.js: inline English catalog updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
